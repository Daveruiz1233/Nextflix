import fs from "fs";
import path from "path";

/**
 * generate-native-rules.mjs — DEPRECATED SHIM
 *
 * The adblock-rules.json files are now generated directly by update-filters.mjs.
 * This file is kept to avoid breaking any scripts that call it, but it's a no-op.
 *
 * Run: node scripts/update-filters.mjs
 * That script generates BOTH filter.bin AND adblock-rules.json in one pass.
 */

const IOS_JSON = path.join(process.cwd(), "ios", "App", "App", "adblock-rules.json");
const ANDROID_JSON = path.join(
  process.cwd(), "android", "app", "src", "main", "assets", "adblock-rules.json"
);

// Verify the files were already generated by update-filters.mjs
if (fs.existsSync(IOS_JSON) && fs.existsSync(ANDROID_JSON)) {
  const stats = fs.statSync(IOS_JSON);
  const rules = JSON.parse(fs.readFileSync(IOS_JSON, "utf8"));
  console.log(`✅ adblock-rules.json already generated by update-filters.mjs`);
  console.log(`   iOS:     ${IOS_JSON} (${rules.length.toLocaleString()} rules, ${(stats.size / 1024 / 1024).toFixed(1)} MB)`);
  console.log(`   Android: ${ANDROID_JSON}`);
} else {
  console.error("❌ adblock-rules.json not found — run update-filters.mjs first");
  process.exit(1);
}
